/**
 * Vendor secret provisioning.
 *
 * Generates:
 *   src/main/core/vendor-public-key.ts   -> Ed25519 public key (safe to ship)
 *   src/main/core/vendor-secrets.json    -> scrypt hash of the vendor master
 *                                           password + the vendor private key
 *                                           sealed with AES-256-GCM under a key
 *                                           derived from that same password.
 *
 * The master password itself is NEVER written anywhere: it is read from the
 * VENDOR_MASTER_PASSWORD environment variable for the duration of this script.
 *
 * Usage: VENDOR_MASTER_PASSWORD='...' npm run vendor:keys
 */
import { generateKeyPairSync, scryptSync, randomBytes, createCipheriv } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SCRYPT = { N: 32768, r: 8, p: 1, keylen: 32, maxmem: 128 * 1024 * 1024 };

export function hashPassword(password: string): string {
  const salt = randomBytes(16);
  const hash = scryptSync(password, salt, SCRYPT.keylen, {
    N: SCRYPT.N,
    r: SCRYPT.r,
    p: SCRYPT.p,
    maxmem: SCRYPT.maxmem
  });
  return `scrypt$${SCRYPT.N}$${SCRYPT.r}$${SCRYPT.p}$${salt.toString('base64')}$${hash.toString('base64')}`;
}

function main() {
  const password = process.env.VENDOR_MASTER_PASSWORD;
  if (!password || password.length < 12) {
    console.error('Set VENDOR_MASTER_PASSWORD (12+ chars) before running this script.');
    process.exit(1);
  }
  const root = join(__dirname, '..');
  const { publicKey, privateKey } = generateKeyPairSync('ed25519');

  const passwordHash = hashPassword(password);

  const keySalt = randomBytes(16);
  const keyIv = randomBytes(12);
  const wrappingKey = scryptSync(password, keySalt, 32, {
    N: SCRYPT.N,
    r: SCRYPT.r,
    p: SCRYPT.p,
    maxmem: SCRYPT.maxmem
  });
  const cipher = createCipheriv('aes-256-gcm', wrappingKey, keyIv);
  const privatePem = privateKey.export({ format: 'pem', type: 'pkcs8' }) as string;
  const ciphertext = Buffer.concat([cipher.update(privatePem, 'utf8'), cipher.final()]);
  const tag = cipher.getAuthTag();

  const secrets = {
    algorithm: 'ed25519',
    passwordHash,
    wrappedPrivateKey: {
      kdf: { name: 'scrypt', N: SCRYPT.N, r: SCRYPT.r, p: SCRYPT.p },
      salt: keySalt.toString('base64'),
      iv: keyIv.toString('base64'),
      tag: tag.toString('base64'),
      ciphertext: ciphertext.toString('base64')
    }
  };

  const publicKeySpki = publicKey.export({ format: 'der', type: 'spki' }).toString('base64');

  writeFileSync(
    join(root, 'src/main/core/vendor-secrets.json'),
    JSON.stringify(secrets, null, 2) + '\n',
    { mode: 0o600 }
  );
  writeFileSync(
    join(root, 'src/main/core/vendor-public-key.ts'),
    `// Generated by scripts/gen-vendor-secrets.ts — do not edit by hand.\n` +
      `export const VENDOR_PUBLIC_KEY_SPKI_BASE64 =\n  '${publicKeySpki}';\n`,
    'utf8'
  );

  console.log('Vendor keys generated.');
  console.log('  public key -> src/main/core/vendor-public-key.ts');
  console.log('  secrets    -> src/main/core/vendor-secrets.json (hash + sealed private key only)');
}

if (require.main === module) main();
